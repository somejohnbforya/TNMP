/**
 * Extracts Rabbit's static renderer (renderToSVG + its dependency closure)
 * into a single vendored file: src/vendor/rabbit-static.js.
 *
 * TNMP stays self-contained: this is a first-party extraction ARTIFACT with
 * provenance, not a live workspace import. Regenerate after upstream Rabbit
 * changes with:  node scripts/extract-rabbit-static.mjs
 */
import { execSync } from 'node:child_process';
import { existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');

// Rabbit lives in the chess workspace; TNMP may sit beside it (~/TNMP) or
// inside it via symlink (~/chess/TNMP). Try both; RABBIT_DIR overrides.
const candidates = [
    process.env.RABBIT_DIR,
    resolve(repoRoot, '../PROMOTE/Rabbit'),
    resolve(repoRoot, '../chess/PROMOTE/Rabbit'),
].filter(Boolean);
const rabbitDir = candidates.find((p) => existsSync(resolve(p, 'src/static.js')));
if (!rabbitDir) {
    console.error(`Rabbit not found. Tried:\n  ${candidates.join('\n  ')}\nSet RABBIT_DIR.`);
    process.exit(1);
}

let commit = 'unknown';
try {
    commit = execSync('git rev-parse --short HEAD', { cwd: rabbitDir, encoding: 'utf8' }).trim();
} catch { /* not a repo — leave 'unknown' */ }

const outfile = resolve(repoRoot, 'src/vendor/rabbit-static.js');
mkdirSync(dirname(outfile), { recursive: true });

const banner = `// Auto-generated by scripts/extract-rabbit-static.mjs — DO NOT EDIT.
// Vendored extraction of Rabbit's static renderer (renderToSVG closure).
// Source: PROMOTE/Rabbit @ ${commit}, extracted ${new Date().toISOString().slice(0, 10)}.
// Regenerate: node scripts/extract-rabbit-static.mjs`;

await build({
    stdin: {
        contents: `export { renderToSVG } from ${JSON.stringify(resolve(rabbitDir, 'src/static.js'))};`,
        resolveDir: repoRoot,
    },
    bundle: true,
    format: 'esm',
    platform: 'browser',
    minify: false, // vite minifies at app build; keep the artifact diffable
    banner: { js: banner },
    outfile,
});

// House-format the artifact so pre-commit's `oxfmt --check src/` passes.
execSync(`npx oxfmt ${JSON.stringify(outfile)}`, { cwd: repoRoot, stdio: 'ignore' });

// Smoke the artifact: it must import cleanly and export the function.
const mod = await import(outfile);
if (typeof mod.renderToSVG !== 'function') {
    console.error('extraction smoke FAILED: renderToSVG export missing');
    process.exit(1);
}
const kb = (await import('node:fs')).statSync(outfile).size / 1024;
console.log(`wrote src/vendor/rabbit-static.js (${kb.toFixed(1)} KB) from Rabbit @ ${commit}`);
